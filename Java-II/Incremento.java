public class Incremento {

  public static void main(String[] args) {
    
    int c;

    c = 5;

    System.out.println(c); // mostra o 5
    System.out.println(c++); // mostra 5 depois
    // incrementa
    System.out.println(c); // mostra 6
    System.out.println(); // so pra pula linha
    
    c = 5;

    System.out.println(c); // mostra o 5
    System.out.println(++c); //pre-incrementa depois
    System.out.println(c); // mostra 6


  } 

}
